import{test,expect,Page}from'@playwright/test';
const nav=(page:Page,name:string)=>page.locator('aside').getByRole('button',{name,exact:true}).first();
const today=()=>{const d=new Date();return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')};
test.beforeEach(async({page})=>{
 await page.goto('/');
 await page.evaluate(()=>localStorage.clear());
 await page.reload();
 await page.getByRole('checkbox',{name:/I have read and understand this private beta notice/i}).check();
 await page.getByRole('button',{name:'Continue to Arc'}).click();
});
test('medication can be added and edited without losing identity or dose history',async({page})=>{
 await nav(page,'You').click();
 await page.getByRole('button',{name:'Add medication'}).click();
 const form=page.locator('.arc-med-form');
 await form.getByLabel('Strength (as labeled)').fill('5 mg');
 await form.getByLabel('Dose per occurrence').fill('1 tablet');
 await form.getByRole('button',{name:'Save medication'}).click();
 const initial=await page.evaluate(()=>JSON.parse(localStorage.getItem('arc.medications.v1')||'{}'));
 expect(initial.medications).toHaveLength(1);
 expect(initial.medications[0].times).toEqual(['08:00','20:00']);
 await page.getByRole('button',{name:'Edit Eliquis (apixaban)'}).click();
 await expect(form.getByLabel('Strength (as labeled)')).toHaveValue('5 mg');
 await form.getByLabel('Strength (as labeled)').fill('2.5 mg');
 await form.getByLabel('Dose per occurrence').fill('2 tablets');
 await form.getByRole('button',{name:'Save changes'}).click();
 const updated=await page.evaluate(()=>JSON.parse(localStorage.getItem('arc.medications.v1')||'{}'));
 expect(updated.medications).toHaveLength(1);
 expect(updated.medications[0].id).toBe(initial.medications[0].id);
 expect(updated.medications[0].strength).toBe('2.5 mg');
 expect(updated.medications[0].dose).toBe('2 tablets');
 await page.reload();
 await nav(page,'You').click();
 await expect(page.locator('.arc-med-item')).toContainText('2.5 mg');
});
test('recorded doses appear in Today inputs, undo restores the same dose',async({page})=>{
 const date=await page.evaluate(()=>{const d=new Date();return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')});
 await page.evaluate(date=>localStorage.setItem('arc.medications.v1',JSON.stringify({medications:[{id:'med-test',name:'Test medication',strength:'5 mg',dose:'1 tablet',times:['08:00','20:00'],startDate:date,calendar:true,active:true}],logs:[{id:'dose-test',medicationId:'med-test',date,time:'08:00',takenAt:new Date().toISOString()}]})),date);
 await page.reload();
 await nav(page,'Today').click();
 const completed=page.locator('.arc-today-completed-meds');
 await expect(completed).toContainText('Test medication');
 await expect(completed).toContainText('1 recorded today');
 await completed.getByRole('button',{name:/Undo recorded dose/}).click();
 await expect(completed).toHaveCount(0);
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('arc.medications.v1')||'{}'));
 expect(after.logs).toHaveLength(0);
 await page.reload();
 await nav(page,'Today').click();
 await expect(page.locator('.arc-today-completed-meds')).toHaveCount(0);
});
test('Calendar dose completion shares logs with Today and medication analytics',async({page})=>{
 const date=await page.evaluate(()=>{const d=new Date();return [d.getFullYear(),String(d.getMonth()+1).padStart(2,'0'),String(d.getDate()).padStart(2,'0')].join('-')});
 await page.evaluate(date=>localStorage.setItem('arc.medications.v1',JSON.stringify({medications:[{id:'med-calendar',name:'Calendar test med',strength:'1 mg',dose:'1 tablet',times:['00:00'],startDate:date,calendar:true,active:true}],logs:[]})),date);
 await page.reload();
 await nav(page,'Calendar').click();
 await page.locator('.cal-switch').getByRole('button',{name:'Day',exact:true}).click();
 await page.locator('.cal-nav').getByRole('button',{name:'Today',exact:true}).click();
 await page.getByRole('button',{name:/Mark taken: Calendar test med/}).click();
 await nav(page,'Today').click();
 await expect(page.locator('.arc-today-completed-meds')).toContainText('Calendar test med');
 await nav(page,'You').click();
 await expect(page.locator('.arc-med-analytics-summary')).toContainText('1/1');
 await page.reload();
 await nav(page,'You').click();
 await expect(page.locator('.arc-med-analytics-summary')).toContainText('1/1');
});
